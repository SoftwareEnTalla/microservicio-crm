  @Mutation(() => ContactResponse<Contact>)
  async createOrUpdateContact(
    @Args("data", { type: () => CreateOrUpdateContactDto })
    data: CreateOrUpdateContactDto
  ): Promise<ContactResponse<Contact>> {
    if (data.id) {
      const existingContact = await this.service.findById(data.id);
      if (existingContact) {
        return this.commandBus.execute(
          new UpdateContactCommand(data, {
            instance: data,
            metadata: {
              initiatedBy:
                (data.input as CreateContactDto | UpdateContactDto).createdBy ||
                'system',
              correlationId: data.id,
            },
          })
        );
      }
    }
    return this.commandBus.execute(
      new CreateContactCommand(data, {
        instance: data,
        metadata: {
          initiatedBy:
            (data.input as CreateContactDto | UpdateContactDto).createdBy ||
            'system',
          correlationId: data.id || uuidv4(),
        },
      })
    );
  }


