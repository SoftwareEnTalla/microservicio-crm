  @Mutation(() => AccountResponse<Account>)
  async createOrUpdateAccount(
    @Args("data", { type: () => CreateOrUpdateAccountDto })
    data: CreateOrUpdateAccountDto
  ): Promise<AccountResponse<Account>> {
    if (data.id) {
      const existingAccount = await this.service.findById(data.id);
      if (existingAccount) {
        return this.commandBus.execute(
          new UpdateAccountCommand(data, {
            instance: data,
            metadata: {
              initiatedBy:
                (data.input as CreateAccountDto | UpdateAccountDto).createdBy ||
                'system',
              correlationId: data.id,
            },
          })
        );
      }
    }
    return this.commandBus.execute(
      new CreateAccountCommand(data, {
        instance: data,
        metadata: {
          initiatedBy:
            (data.input as CreateAccountDto | UpdateAccountDto).createdBy ||
            'system',
          correlationId: data.id || uuidv4(),
        },
      })
    );
  }


